package ATB15X_JavaTest_11jan2026;

public class Print_Numbers_Using_dowhile {
    // Write a Java program to print numbers from 1 to 10 using a do-while loop.
    static void main() {
        int i=1;
        do {

                System.out.println(i);
                i++;

        }while (i <= 10);
    }
}
